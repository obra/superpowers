CREATE TABLE VIN_MAKE (
    VIN_MAKE_ID NUMBER PRIMARY KEY,
    NAME_MAKE VARCHAR2(200),
    NAME_MAKE_EN VARCHAR2(200),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(100),
    CREATION_DATE DATE DEFAULT SYSDATE,
    MODIFIED_BY VARCHAR2(100),
    MODIFICATION_DATE DATE
);

CREATE TABLE VIN_MODEL (
    VIN_MODEL_ID NUMBER PRIMARY KEY,
    VIN_MAKE_ID NUMBER NOT NULL,
    NAME_MODEL VARCHAR2(200),
    NAME_MODEL_EN VARCHAR2(200),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(100),
    CREATION_DATE DATE DEFAULT SYSDATE,
    MODIFIED_BY VARCHAR2(100),
    MODIFICATION_DATE DATE,
    CONSTRAINT FK_VIN_MODEL_MAKE FOREIGN KEY (VIN_MAKE_ID)
        REFERENCES VIN_MAKE (VIN_MAKE_ID)
);

CREATE TABLE VIN_ESKA_MAPPING (
    MAPPING_ID NUMBER PRIMARY KEY,
    VIN_MAKE_ID NUMBER NOT NULL,
    VIN_MODEL_ID NUMBER NOT NULL,
    ESKA_MAKE_ID NUMBER,
    ESKA_MAKE_NAME VARCHAR2(200),
    ESKA_MODEL_ID NUMBER,
    ESKA_MODEL_NAME VARCHAR2(200),
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(100),
    CREATION_DATE DATE DEFAULT SYSDATE,
    MODIFIED_BY VARCHAR2(100),
    MODIFICATION_DATE DATE,
    CONSTRAINT FK_MAPPING_MAKE FOREIGN KEY (VIN_MAKE_ID)
        REFERENCES VIN_MAKE (VIN_MAKE_ID),
    CONSTRAINT FK_MAPPING_MODEL FOREIGN KEY (VIN_MODEL_ID)
        REFERENCES VIN_MODEL (VIN_MODEL_ID)
);

CREATE INDEX IX_VIN_MODEL_MAKE ON VIN_MODEL (VIN_MAKE_ID);
CREATE INDEX IX_VIN_MAPPING_MODEL ON VIN_ESKA_MAPPING (VIN_MODEL_ID);
CREATE INDEX IX_VIN_MAPPING_STATUS ON VIN_ESKA_MAPPING (STATUS);

CREATE UNIQUE INDEX UX_VIN_ESKA_ACTIVE_MAPPING
ON VIN_ESKA_MAPPING (
    CASE WHEN STATUS = 'ACTIVE' THEN VIN_MAKE_ID END,
    CASE WHEN STATUS = 'ACTIVE' THEN VIN_MODEL_ID END
);

CREATE OR REPLACE VIEW VIN_MASTER_SHEET AS
SELECT
    MK.VIN_MAKE_ID,
    MK.NAME_MAKE,
    MK.NAME_MAKE_EN,
    MD.VIN_MODEL_ID,
    MD.NAME_MODEL,
    MD.NAME_MODEL_EN,
    MP.ESKA_MAKE_ID,
    MP.ESKA_MAKE_NAME,
    MP.ESKA_MODEL_ID,
    MP.ESKA_MODEL_NAME,
    CASE
        WHEN MP.MAPPING_ID IS NULL THEN 'UNMAPPED'
        WHEN MP.STATUS = 'INACTIVE' THEN 'INACTIVE'
        ELSE 'MAPPED'
    END AS STATUS,
    NVL(MP.CREATED_BY, MD.CREATED_BY) AS CREATED_BY,
    NVL(MP.CREATION_DATE, MD.CREATION_DATE) AS CREATION_DATE,
    NVL(MP.MODIFIED_BY, MD.MODIFIED_BY) AS MODIFIED_BY,
    NVL(MP.MODIFICATION_DATE, MD.MODIFICATION_DATE) AS MODIFICATION_DATE
FROM VIN_MAKE MK
JOIN VIN_MODEL MD
    ON MD.VIN_MAKE_ID = MK.VIN_MAKE_ID
LEFT JOIN VIN_ESKA_MAPPING MP
    ON MP.VIN_MAKE_ID = MK.VIN_MAKE_ID
   AND MP.VIN_MODEL_ID = MD.VIN_MODEL_ID
   AND MP.STATUS IN ('ACTIVE', 'INACTIVE');

